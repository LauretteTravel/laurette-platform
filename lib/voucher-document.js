export function voucherDocument(snapshot, state) {
  const d = snapshot.data,
    language = d.language === "en" ? "en" : "ar",
    l = LABELS[language];
  const field = (label, value) =>
    `<div class="vd-field"><b>${esc(label)}</b><span dir="auto">${esc(value || "—")}</span></div>`;
  const people = `<section class="vd-block"><h2>${l.people}</h2><table><thead><tr><th>${l.name}</th>${snapshot.kind === "flight" ? `<th>${l.ticket}</th>` : ""}</tr></thead><tbody>${d.people.map((p) => `<tr><td dir="auto">${esc(p.name)}</td>${snapshot.kind === "flight" ? `<td dir="auto">${esc(p.ticketNumber || "—")}</td>` : ""}</tr>`).join("")}</tbody></table></section>`;
  const details =
    snapshot.kind === "flight"
      ? `${field(l.airline, d.flight.airline)}${field(l.baggage, d.flight.baggage)}${d.flight.segments.map((s) => `<section class="vd-block vd-segment"><h2>${l.flightNumber}: ${esc(s.flightNumber)}</h2><div class="vd-grid">${field(l.from, s.from)}${field(l.to, s.to)}${field(l.from, s.departAt + " · " + s.departZone)}${field(l.to, s.arriveAt + " · " + s.arriveZone)}</div></section>`).join("")}`
      : `<section class="vd-block"><h2>${esc(d.hotel.name)}</h2><div class="vd-grid">${field(l.address, d.hotel.address)}${field(l.room, d.hotel.roomType)}${field(l.checkIn, d.hotel.checkIn + " " + d.hotel.checkInTime)}${field(l.checkOut, d.hotel.checkOut + " " + d.hotel.checkOutTime)}${field(l.nights, String(d.hotel.nights))}${field(l.guests, String(d.hotel.guestCount))}${field(l.meals, d.hotel.mealPlan)}</div><h3>${l.cancellation}</h3><p dir="auto">${esc(d.hotel.cancellationPolicy)}</p></section>`;
  return `<!doctype html><html lang="${language}" dir="${language === "ar" ? "rtl" : "ltr"}"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><meta name="robots" content="noindex,nofollow"><title>${esc(snapshot.reference)} · ${l[snapshot.kind]}</title><link rel="stylesheet" href="/assets/fonts/cairo.css"><link rel="stylesheet" href="/assets/css/voucher-ledger.css"></head><body class="vd-document" data-filename="${esc(snapshot.reference)}-v${snapshot.version}"><nav class="vd-controls" aria-label="Document controls"><button id="vdPdf">${l.pdf}</button><button id="vdPrint">${l.print}</button><span id="vdStatus" role="status" aria-live="polite"></span></nav><article id="vdSheet" class="vd-sheet"><header class="vd-header vd-block"><img src="${esc(snapshot.brand.logo)}" width="170" height="65" alt="Laurette Travel"><div><h1>${l[snapshot.kind]}</h1><p>${esc(snapshot.brand.name)}</p></div></header><p class="vd-state ${state === "confirmed" ? "" : "vd-warning"}">${l[state] || l.review}</p><div class="vd-grid vd-block">${field(l.reference, snapshot.reference)}${field(l.version, String(snapshot.version))}${field(l.request, snapshot.requestReference)}${field(l.booking, d.bookingReference)}${field(l.issued, new Intl.DateTimeFormat(language === "ar" ? "ar-JO" : "en-GB", { timeZone: "Asia/Amman", dateStyle: "medium", timeStyle: "short" }).format(new Date(snapshot.issuedAt)) + " · Asia/Amman")}</div>${people}${details}${d.notes ? `<section class="vd-block"><h2>${l.notes}</h2><p dir="auto">${esc(d.notes)}</p></section>` : ""}<footer class="vd-footer vd-block"><p>${esc(snapshot.brand.phone)} ${esc(snapshot.brand.email)}</p><p>${l.hint}</p><small dir="ltr">${esc(snapshot.reference)} · v${snapshot.version}</small></footer></article><script src="/assets/js/voucher-document.js" defer></script></body></html>`;
}
